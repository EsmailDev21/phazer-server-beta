/** OWNER > ADMIN > MEMBER > VIEWER > CLIENT, per the graph's exact ordering. */
export const ROLE_RANK: Record<Role, number> = {
  OWNER: 4,
  ADMIN: 3,
  MEMBER: 2,
  VIEWER: 1,
  CLIENT: 0,
};

export function mostPermissiveRole(roles: Role[]): Role {
  return roles.reduce((best, current) =>
    ROLE_RANK[current] > ROLE_RANK[best] ? current : best,
  );
}
